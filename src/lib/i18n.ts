const DICTIONARIES: Record<Language, Record<TranslationKey, string>> = { ru, en };

/** Every key there is. Used by the tests to check both dictionaries are whole. */
export const TRANSLATION_KEYS = Object.keys(ru) as TranslationKey[];

export type TranslateParams = Record<string, string | number>;

/** Substitutes `{name}` placeholders. Unknown keys fall through visibly. */
export function translate(
  language: Language,
  key: TranslationKey,
  params?: TranslateParams,
): string {
  const template = DICTIONARIES[language]?.[key] ?? DICTIONARIES.en[key] ?? key;
  if (!params) return template;

  return template.replace(/\{(\w+)\}/g, (whole, name: string) =>
    name in params ? String(params[name]) : whole,
  );
}

/** Normalises whatever is in the config to a language we actually have. */
export function asLanguage(value: string | undefined | null): Language {
  return value === 'en' ? 'en' : 'ru';
}

export type Translate = (key: TranslationKey, params?: TranslateParams) => string;

/** The translator for the currently configured language. */
export function useT(): Translate {
  const language = useApp((s) => asLanguage(s.config?.language));
  return useCallback<Translate>((key, params) => translate(language, key, params), [language]);
}
